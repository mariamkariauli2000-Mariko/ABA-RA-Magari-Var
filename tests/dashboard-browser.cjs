/* Optional browser regression test: requires Playwright and installed Chrome. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { spawn, execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'job-journal-browser-'));
const database = path.join(temporary, 'jobs.sqlite3');
const shots = path.join(root, 'data', 'qa');
fs.mkdirSync(shots, { recursive: true });
let server, browser;
const cli = (...args) => JSON.parse(execFileSync('python3', [path.join(root, 'scripts/jobs.py'), '--db', database, ...args], { encoding:'utf8' }));

(async()=>{
  server = spawn('python3', ['scripts/serve.py', '--db', database, '--port', '0'], { cwd:root, stdio:['ignore','pipe','pipe'] });
  const base = await new Promise((resolve,reject)=>{
    const timeout = setTimeout(()=>reject(new Error('Dashboard server did not start')),10000);
    server.stdout.on('data',chunk=>{const match=String(chunk).match(/http:\/\/127\.0\.0\.1:\d+/);if(match){clearTimeout(timeout);resolve(match[0]);}});
    server.once('exit',code=>reject(new Error('Server exited: '+code)));
  });
  browser = await chromium.launch({ channel:'chrome', headless:true });
  const page = await browser.newPage({ viewport:{width:1560,height:1000}, deviceScaleFactor:1 });
  page.setDefaultTimeout(10000);
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
  await page.goto(base);
  await page.getByRole('heading',{name:'Opportunities',exact:true}).waitFor();
  await page.getByRole('button',{name:'Add job',exact:true}).click();
  await page.getByLabel('Job title',{exact:true}).fill('Customer Support Lead');
  await page.getByLabel('Company',{exact:true}).fill('Example Company');
  await page.getByLabel('Location',{exact:true}).fill('Remote · Europe');
  await page.getByLabel('Listing URL',{exact:true}).fill('https://example.invalid/jobs/support-lead');
  await page.locator('#add-form select[name="remote_status"]').selectOption('remote');
  await page.getByLabel('Description optional').fill('Synthetic role for browser verification. Work with a thoughtful remote team and help customers succeed.');
  await page.getByRole('button',{name:'Add opportunity',exact:true}).click();
  await page.getByRole('heading',{name:'Customer Support Lead',exact:true}).waitFor();
  await page.getByRole('textbox',{name:'Your notes for this job'}).fill('Ask about timezone overlap and the support rotation.');
  await page.getByText('All changes saved',{exact:true}).waitFor();
  await page.getByRole('textbox',{name:'Write a comment'}).fill('Interesting role. Revisit after reading the company handbook.');
  await page.getByRole('button',{name:'Add comment',exact:true}).click();
  await page.getByText('Interesting role. Revisit after reading the company handbook.',{exact:true}).waitFor();
  await page.getByLabel('Job status',{exact:true}).selectOption('shortlisted');
  await page.getByText('Moved to Shortlisted',{exact:true}).waitFor();
  await page.screenshot({path:path.join(shots,'job-detail.png')});
  await page.getByRole('button',{name:'Close job details'}).click();
  await page.reload();
  await page.getByRole('button',{name:'Customer Support Lead',exact:true}).click();
  assert.equal(await page.getByRole('textbox',{name:'Your notes for this job'}).inputValue(),'Ask about timezone overlap and the support rotation.');
  assert.equal(await page.getByLabel('Job status',{exact:true}).inputValue(),'shortlisted');
  await page.getByRole('textbox',{name:'Your notes for this job'}).fill('A final thought saved while closing the panel.');
  await page.getByRole('button',{name:'Close job details'}).click();
  await page.locator('#job-dialog').waitFor({state:'hidden'});
  await page.getByRole('button',{name:'Customer Support Lead',exact:true}).click();
  assert.equal(await page.getByRole('textbox',{name:'Your notes for this job'}).inputValue(),'A final thought saved while closing the panel.');
  await page.getByRole('button',{name:'Reviewed',exact:true}).click();
  await page.getByRole('button',{name:'Mark reviewed',exact:true}).waitFor();
  await page.getByRole('button',{name:'Close job details'}).click();
  await page.locator('[data-view="unreviewed"]').click();
  await page.getByRole('button',{name:'Customer Support Lead',exact:true}).waitFor();
  await page.locator('[data-view="board"]').click();
  await page.locator('.job-card').dragTo(page.locator('[data-column="applied"] .column-body'));
  await page.locator('[data-column="applied"] .job-card').waitFor();

  await page.locator('[data-view="profile"]').click();
  await page.getByLabel('Your name',{exact:true}).fill('Browser Test');
  await page.getByLabel('Professional headline',{exact:true}).fill('Operations & customer success');
  await page.getByLabel('Target roles',{exact:true}).fill('Support Lead, Operations Manager');
  await page.getByLabel('Skills & strengths',{exact:true}).fill('Customer success, Operations');
  await page.getByLabel('Where you’re based',{exact:true}).fill('Tbilisi, Georgia');
  await page.getByRole('button',{name:'Save profile',exact:true}).first().click();
  await page.getByText('Profile saved. Your next search will use it.',{exact:true}).waitFor();
  await page.screenshot({path:path.join(shots,'search-profile.png'),fullPage:true});
  const profile=cli('profile','show');
  assert.deepEqual(profile.profile.roles,['Support Lead','Operations Manager']);
  const run=cli('run','start','--request','Browser test: saved profile');
  assert.equal(cli('run','show',run.run_id).profile_snapshot.profile.location,'Tbilisi, Georgia');

  const token=await page.locator('meta[name="workspace-token"]').getAttribute('content');
  for(const [i,title,status] of [[1,'Customer Success Manager','new'],[2,'Operations Specialist','new'],[3,'Community & Support Lead','shortlisted'],[4,'Business Operations Manager','interviewing'],[5,'Customer Experience Lead','offer'],[6,'Support Operations Analyst','applied']]){
    const response=await page.request.post(base+'/api/jobs',{headers:{'X-Workspace-Token':token},data:{job:{title,company:i%2?'Example Studio':'Demo Works',source_url:`https://example.invalid/jobs/${i}`,location_text:i%2?'Remote · Worldwide':'Remote · EMEA',remote_status:'remote',salary_min:60000+i*5000,salary_max:90000+i*5000,salary_currency:'USD',salary_period:'year',skills:['Operations','Customer success']},status}});
    assert.equal(response.status(),201);
  }
  await page.locator('[data-view="sources"]').click();
  const sourceSwitch=page.locator('[data-source]').first();
  await sourceSwitch.uncheck();
  await page.getByText('Source updated',{exact:true}).waitFor();
  await page.locator('[data-view="board"]').click();
  await page.getByRole('button',{name:'Customer Success Manager',exact:true}).waitFor();
  await page.screenshot({path:path.join(shots,'kanban-board.png')});
  await page.locator('#job-search').fill('Customer Success Manager');
  assert.equal(await page.locator('.job-card').count(),1);
  await page.locator('#job-search').fill('');
  await page.getByRole('button',{name:'List',exact:true}).click();
  assert.equal(await page.locator('.jobs-table tbody tr').count(),7);
  await page.getByRole('button',{name:'Board',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Page overflows the mobile viewport');
  await page.screenshot({path:path.join(shots,'mobile-board.png')});
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await page.locator('[data-view="profile"]').click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Profile overflows the mobile viewport');
  await page.getByLabel('Target roles',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,checks:['manual entry','notes persist after reload','comments','status changes','reviewed filter','drag and drop','editable profile','CLI profile snapshot','source switches','search','list view','mobile layouts','no browser errors'],screenshots:shots,personalDatabaseTouched:false},null,2));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{await browser?.close();server?.kill();fs.rmSync(temporary,{recursive:true,force:true});});
